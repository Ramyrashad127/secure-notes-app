class SecureNotesUser(HttpUser):
    """Realistic journey: register ONCE, then repeatedly log in and churn notes."""

    wait_time = between(1, 5)
    weight = 4

    def on_start(self) -> None:
        self.email = f"locust-{uuid.uuid4().hex[:12]}@example.com"
        self.password = "LocustPass1!"
        self.registered = False

    @task
    def full_journey(self) -> None:
        # Register only once per user. Registering repeatedly with the same
        # email after a successful sign-up would otherwise be 307-redirected by
        # the auth-route guard (once a session cookie exists) and never reach
        # the register action / rate limiter.
        if not self.registered:
            registered = post_action(
                self, "registerAction", "/register",
                {"email": self.email, "password": self.password},
            )
            if not registered:
                # Shared host IP may already be throttled by the probe class.
                return
            self.registered = True

        # Logout, then log back in to exercise password verification + login limiter.
        post_action(self, "logoutAction", "/notes", [])
        self.client.get("/login", name="/login (page)")
        logged_in = post_action(
            self, "loginAction", "/login",
            {"email": self.email, "password": self.password},
        )
        if not logged_in:
            return

        # Heavy DB churn: create notes and force autosave + manual snapshots.
        for _ in range(3):
            created = post_action(
                self, "createNoteAction", "/notes",
                {"title": f"Locust note {uuid.uuid4().hex[:6]}", "content": "Seed content"},
            )
            note_id = ((created or {}).get("note") or {}).get("id")
            if not note_id:
                continue

            post_action(
                self, "updateNoteAction", f"/notes/{note_id}",
                {
                    "id": note_id,
                    "title": f"Autosaved {uuid.uuid4().hex[:6]}",
                    "content": "Autosave body.",
                    "clientUpdatedAt": utc_now_iso(),
                    "isManualSave": False,
                },
            )
            post_action(
                self, "updateNoteAction", f"/notes/{note_id}",
                {
                    "id": note_id,
                    "title": "Manual save",
                    "content": "Final body.",
                    "clientUpdatedAt": utc_now_iso(),
                    "isManualSave": True,
                },
            )

        self.client.get("/notes", name="/notes (page)")


class RateLimitProbeUser(HttpUser):
    """Deliberately hammer the rate-limited endpoints to force Valkey 429s."""

    wait_time = between(1, 5)
    weight = 1

    def on_start(self) -> None:
        self.email = f"probe-{uuid.uuid4().hex[:8]}@example.com"
        self.password = "ProbePass1!x"  # wrong on purpose: always fails login

    @task
    def hammer_login(self) -> None:
        # Wrong credentials against a fixed email so every attempt reaches the
        # login action (never a redirect), failing auth and incrementing the
        # (ip:email) bucket until Valkey answers with "Too many attempts".
        post_action(
            self, "loginAction", "/login",
            {"email": self.email, "password": self.password},
        )

    @task
    def hammer_register(self) -> None:
        # Clear the session so the proxy never 307-redirects an authenticated
        # client away from /register; the register action (and its IP bucket)
        # then runs every time. A fresh email each attempt keeps the system
        # from short-circuiting on a duplicate-email response for the probe.
        self.client.cookies.clear()
        fresh_email = f"probe-{uuid.uuid4().hex[:10]}@example.com"
        post_action(
            self, "registerAction", "/register",
            {"email": fresh_email, "password": "ProbePass1!"},
        )